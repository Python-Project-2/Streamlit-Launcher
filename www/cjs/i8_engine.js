    /* ====== I18N ENGINE — toggle ID ⇄ 中文, localStorage, event re-render ====== */
    (function () {
      var DICT = window.SL_DICT || {};
      var LANGS = ['id', 'zh'];
      function norm(l) { return LANGS.indexOf(l) >= 0 ? l : 'id'; }
      var saved = null;
      try { saved = localStorage.getItem('sl-lang'); } catch (e) { }
      var initial = 'id';
      if (saved && LANGS.indexOf(saved) >= 0) initial = saved;
      else if (navigator.language && String(navigator.language).toLowerCase().indexOf('zh') === 0) initial = 'zh';
      var CUR = norm(initial);

      function t(key, vars) {
        var e = DICT[key];
        if (!e) return undefined;
        var s = (e[CUR] !== undefined) ? e[CUR] : e.id;
        if (vars) {
          for (var k in vars) {
            if (Object.prototype.hasOwnProperty.call(vars, k)) s = s.split('{' + k + '}').join(String(vars[k]));
          }
        }
        return s;
      }

      function apply(lang, persist) {
        CUR = norm(lang);
        document.documentElement.lang = (CUR === 'zh') ? 'zh-CN' : 'id';
        var tt = t('meta.title');
        if (tt) document.title = tt;
        var md = document.querySelector('meta[name="description"]');
        if (md && t('meta.desc')) md.setAttribute('content', t('meta.desc'));
        var i, el, v;
        var list = document.querySelectorAll('[data-i18n]');
        for (i = 0; i < list.length; i++) { el = list[i]; v = t(el.getAttribute('data-i18n')); if (v !== undefined) el.textContent = v; }
        list = document.querySelectorAll('[data-i18n-html]');
        for (i = 0; i < list.length; i++) { el = list[i]; v = t(el.getAttribute('data-i18n-html')); if (v !== undefined) el.innerHTML = v; }
        list = document.querySelectorAll('[data-i18n-aria]');
        for (i = 0; i < list.length; i++) { el = list[i]; v = t(el.getAttribute('data-i18n-aria')); if (v !== undefined) el.setAttribute('aria-label', v); }
        list = document.querySelectorAll('[data-i18n-attr]');
        for (i = 0; i < list.length; i++) {
          el = list[i];
          var spec = (el.getAttribute('data-i18n-attr') || '').split(';');
          for (var j = 0; j < spec.length; j++) {
            var pair = spec[j].split(':');
            if (pair.length === 2 && pair[0] && pair[1]) {
              var av = t(pair[1]);
              if (av !== undefined) el.setAttribute(pair[0], av);
            }
          }
        }
        var btns = document.querySelectorAll('.lang-btn');
        for (i = 0; i < btns.length; i++) { btns[i].classList.toggle('active', btns[i].getAttribute('data-lang') === CUR); }
        if (persist !== false) { try { localStorage.setItem('sl-lang', CUR); } catch (e) { } }
        document.dispatchEvent(new CustomEvent('sl:languagechange', { detail: { lang: CUR } }));
      }

      window.SL_T = t;
      Object.defineProperty(window, 'SL_LANG', { get: function () { return CUR; } });

      var btns = document.querySelectorAll('.lang-btn');
      for (var b = 0; b < btns.length; b++) {
        (function (btn) {
          btn.addEventListener('click', function () {
            if (btn.getAttribute('data-lang') !== CUR) apply(btn.getAttribute('data-lang'));
          });
        })(btns[b]);
      }

      apply(initial, false);
    })();